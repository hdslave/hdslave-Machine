"""Build the fixed native-size bitmaps. Run at the repository root with Pillow."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

out = ['// Generated by tools/ui_preview/fonts.py. See assets/fonts for OFL licences.',
       '#pragma once', '#include <cstdint>', 'namespace machine::ui::font {']
for family, path, size, height, offset in [
    ('body','departure/DepartureMono-Regular.otf',11,12,3),
    ('title','audiowide/Audiowide-Regular.ttf',21,18,6)]:
    f = ImageFont.truetype('assets/fonts/' + path, size)
    widths, records = [], []
    for n in range(32,128):
        c = chr(n) if n < 127 else '·'
        w = round(f.getlength(c))
        im = Image.new('L',(32,height))
        ImageDraw.Draw(im).text((0,-offset), c, font=f, fill=255)
        widths.append(w)
        records.append('{' + ','.join(hex(sum(1 << x for x in range(32) if im.getpixel((x,y)) >= 90)) for y in range(height)) + '}')
    out += [f'inline constexpr uint8_t {family}Width[] = {{' + ','.join(map(str,widths)) + '};',
            f'inline constexpr uint32_t {family}[][ {height} ] = {{', ',\n'.join(records), '};']
out.append('}')
Path('ui/fonts.h').write_text('\n'.join(out)+'\n')
