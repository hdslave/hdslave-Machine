"""Reduce the original ImageGen sheets and pack native PNGs into indexed C++ arrays."""
from pathlib import Path
from PIL import Image

dest = Path("assets/art")
dest.mkdir(exist_ok=True)
names = "fm bd sd cp hh cy-cb efm gnd kit".split()
# Hand-selected inks in panel space. Index zero is paper transparency.
swatches = "000000 281830 392044 52305a 634073 84519c 9c71ad b59abd d6c3de f7ebef 293c52 426d84 63a6b5 94dbd6 211431 311852 522873 733c94".split()
def panel(s):
    rgb = bytes.fromhex(s)
    rr, gg, bb = rgb[0] >> 3, rgb[1] >> 2, rgb[2] >> 3
    return (rr << 3 | rr >> 2, gg << 2 | gg >> 4, bb << 3 | bb >> 2)
colors = list(map(panel,swatches))
def indexed(im):
    ix = Image.new('P',im.size)
    ix.putpalette(bytes(channel for rgb in colors for channel in rgb))
    ix.putdata([min(range(len(colors)),key=lambda i:sum((a-b)**2 for a,b in zip(rgb,colors[i]))) for rgb in im.getdata()])
    ix.info['transparency']=0
    return ix
src = Image.open('assets/explore/emblem-atlas.png').convert('RGB')
# The original is optically spaced. Hand-fit its row gutters before automatic ink trimming.
hcuts=[0, 0.33, 0.645, 1]
for i,name in enumerate(names):
    col,row=i%3,i//3
    tile=src.crop((src.width*col//3, round(src.height*hcuts[row]), src.width*(col+1)//3, round(src.height*hcuts[row+1])))
    mask=tile.convert('L').point(lambda p: 255 if p>28 else 0)
    tile=tile.crop(mask.getbbox())
    tile.thumbnail((28,28),Image.Resampling.LANCZOS)
    icon=Image.new('RGB',(30,30))
    icon.paste(tile,((30-tile.width)//2,(30-tile.height)//2))
    im=indexed(icon)
    im.save(dest/(name+'.png'),optimize=False)

band=Image.open('assets/explore/phase-band.png').convert('RGB').resize((124,30),Image.Resampling.LANCZOS)
band=band.point(lambda n:round(n*.79))
indexed(band).save(dest/'phase-band.png')
def dump(p):
    im=Image.open(dest/(p+'.png'))
    data=list(im.getdata())
    return '{\n'+',\n'.join(','.join(map(str,data[i:i+im.width])) for i in range(0,len(data),im.width))+'\n}'
inks=','.join('0xff%02x%02x%02x'%c for c in colors)
Path('ui/art.h').write_text('// Original artwork for hdslave Machine. Generated by tools/ui_preview/art.py.\n#pragma once\n#include <cstdint>\nnamespace machine::ui::art {\n'
  +'inline constexpr int size=30, bandWidth=124, bandHeight=30;\ninline constexpr uint32_t inks[]={'+inks+'};\n'
  +'inline constexpr uint8_t icons[9][size*size]={\n'+',\n'.join(map(dump,names))+'};\n'
  +'inline constexpr uint8_t band[]='+dump('phase-band')+';\n}\n')
